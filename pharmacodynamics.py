"""
===============================================================================
PHARMACODYNAMICS.PY
Smart AI Infusion Pump - Mechanistic Digital Twin

Purpose
-------
This module converts the simulated plasma concentration (Cp) of
norepinephrine, obtained from the pharmacokinetic (PK) model,
into its corresponding pharmacodynamic (PD) effect.

To achieve this, the standard Emax (Hill) model is used:

                    Emax × Cp^γ
E(Cp) = ----------------------------------
                   EC50^γ + Cp^γ

where:
    Cp    = Plasma drug concentration
    Emax  = Maximum achievable drug effect
    EC50  = Concentration producing 50% of Emax
    γ     = Hill coefficient controlling curve steepness

Why this model?
---------------
The Emax (Hill) equation is one of the most widely accepted
pharmacodynamic models because it realistically represents the
saturating behaviour of drugs. As plasma concentration increases,
drug effect increases rapidly at first and then gradually approaches
a physiological maximum (Emax), rather than increasing indefinitely.

Project-specific assumptions
----------------------------
The mathematical structure of the Emax model is well established in the
literature and has been applied to describe the relationship between
norepinephrine concentration and mean arterial pressure (MAP).

However, the exact values of EC50, Emax, and the Hill coefficient for
the specific patient population considered in this project were not
available in the accessible literature. Therefore, the parameter values
defined in constants.py are explicitly stated assumptions.

These assumed values were carefully calibrated so that the resulting
drug-response curve remains physiologically realistic over the plasma
concentration range generated by the pharmacokinetic model.

The complete justification for these assumptions is documented in
constants.py.
===============================================================================
"""

import constants as c


def compute_drug_effect(cp):
    """
    Converts plasma concentration (Cp) into a normalized
    pharmacodynamic effect using the Emax (Hill) equation.

    Parameters
    ----------
    cp : float
        Plasma concentration predicted by the pharmacokinetic model.

    Returns
    -------
    float
        Dimensionless drug effect (0–Emax).

    Explanation
    ----------------------------
    The returned value does not directly represent blood pressure.
    Instead, it represents the fraction of the maximum possible
    pharmacological effect produced by the current plasma concentration.

    This normalized effect is subsequently passed to the cardiovascular
    model, where it increases systemic vascular resistance (SVR),
    thereby reproducing the vasoconstrictive action of norepinephrine.

    Specifically, cardiovascular.py applies:

        SVR = SVR0 × (1 + E)

    where E is the value calculated in this function.
    """

    # A non-positive plasma concentration cannot produce a
    # pharmacological response, so the drug effect is set to zero.
    if cp <= 0:
        return 0.0

    # Raise the plasma concentration to the Hill coefficient.
    # This introduces the characteristic sigmoidal relationship
    # between concentration and effect.
    cp_g = cp ** c.HILL_COEFFICIENT_ASSUMED

    # Apply the same exponent to EC50 so that both numerator
    # and denominator follow the standard Hill equation.
    ec50_g = c.EC50_ASSUMED ** c.HILL_COEFFICIENT_ASSUMED

    # Compute the normalized pharmacodynamic effect using
    # the standard Emax (Hill) model.
    return c.EMAX_ASSUMED * cp_g / (ec50_g + cp_g)