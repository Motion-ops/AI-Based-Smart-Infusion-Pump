"""
===============================================================================
GENERATE_DATASET.PY
Smart AI Infusion Pump - Mechanistic Digital Twin

Purpose
-------
This module generates the datasets used to train and evaluate the
artificial intelligence components of the smart infusion pump.

The virtual patient population is simulated using the mechanistic
digital twin. At every simulation step, physiological measurements,
controller decisions, and patient outcomes are recorded to construct
machine-learning datasets.

Two independent prediction tasks are supported:

1. Infusion Advisory Model
   Learns to imitate the expert controller by predicting the
   recommended norepinephrine infusion rate from observable bedside
   measurements.

2. Early Risk Prediction Model
   Learns to predict whether the patient's condition will deteriorate
   within a predefined future time window using both current
   measurements and short-term physiological trends.

Dataset design philosophy
-------------------------
Only information that would realistically be available to a clinical
decision-support system is included as AI input features.

Internal physiological variables generated by the digital twin, such as
systemic vascular resistance, plasma drug concentration, and drug
effect, are retained solely as hidden ground-truth variables for model
evaluation and are intentionally excluded from AI training inputs.

The complete justification for all feature selections is documented in
constants.py.
===============================================================================
"""

import random
from collections import deque

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

import constants as c
from digital_twin import VirtualPatient
from patient_generator import PROFILE_WEIGHTS
from expert_controller import expert_controller, EMERGENCY_MAP_MMHG


# Columns legitimately observable by a real pump/bedside monitor -
# used by the imitation-style action/flow advisory models. See module
# docstring for why WeightKg/Age are included and Sex/Profile/SAPS_II
# are not.
FEATURE_COLUMNS = [
    "MeasuredMAP", "MeasuredHR", "MeasuredSpO2", "FlowRate",
    "WeightKg", "Age", "TargetBP",
    "MeasuredBP_Error", "MeasuredBP_Trend", "MeasuredShockIndex",
    "MeasuredPerfusionIndex", "MeasuredOxygenDeficit"
]
LABEL_COLUMN = "RecommendedFlow"

# Rolling-window features + label for the independent risk/early-
# warning model. Superset of FEATURE_COLUMNS, same as V1.
ROLLING_FEATURE_COLUMNS = [
    "RollMeanMAP", "RollStdMAP", "RollSlopeMAP",
    "RollMeanSpO2", "RollStdSpO2", "RollSlopeSpO2",
    "RollMeanHR", "RollSlopeHR"
]
RISK_FEATURE_COLUMNS = FEATURE_COLUMNS + ROLLING_FEATURE_COLUMNS
RISK_LABEL_COLUMN = "WillDeteriorate"

WINDOW = 30       # ticks of history used for rolling features
LOOKAHEAD = 30    # ticks into the future checked for the risk label

# Realistic sensor measurement error, applied to what the AI actually
# sees. [ASSUMPTION, unchanged from V1] generic monitor-noise
# magnitudes, not literature-calibrated for this specific twin swap.
BP_NOISE_SD = 3.0
HR_NOISE_SD = 2.0
SPO2_NOISE_SD = 1.0


def _profile_assignment(num_patients, seed):
    names = list(PROFILE_WEIGHTS.keys())
    weights = [PROFILE_WEIGHTS[n] for n in names]
    total_weight = sum(weights)
    counts = [round(num_patients * w / total_weight) for w in weights]
    diff = num_patients - sum(counts)
    counts[0] += diff
    assignment = []
    for name, cnt in zip(names, counts):
        assignment.extend([name] * cnt)
    rng = random.Random(seed)
    rng.shuffle(assignment)
    return assignment


def _rolling_slope(buffer):
    """Least-squares slope of a short buffer, treated as evenly spaced
    in time. O(n) - fine for small windows like WINDOW=30."""
    n = len(buffer)
    if n < 2:
        return 0.0
    x = np.arange(n, dtype=float)
    y = np.asarray(buffer, dtype=float)
    x_mean, y_mean = x.mean(), y.mean()
    denom = ((x - x_mean) ** 2).sum()
    if denom == 0:
        return 0.0
    return float(((x - x_mean) * (y - y_mean)).sum() / denom)


def generate_dataset(num_patients, sim_time, seed, output_file):
    random.seed(seed)
    np.random.seed(seed)

    profile_assignment = _profile_assignment(num_patients, seed)

    rows = []
    print(f"Generating {num_patients} virtual patients (seed={seed}) -> {output_file}")

    for patient_id in range(num_patients):
        # Sample this patient's target MAP across the SEPSISPAM-studied
        # range (constants.py) rather than fixing it at the 65 mmHg SSC
        # default - without this, TargetBP has zero variance in training
        # data and the AI advisory models cannot learn anything about it
        # (see module docstring / constants.py for the citation).
        target_map = random.uniform(*c.TARGET_MAP_RANGE_MMHG)

        patient = VirtualPatient(
            patient_id,
            profile=profile_assignment[patient_id],
            seed=seed * 100_003 + patient_id,  # deterministic-but-distinct per patient
            target_map=target_map
        )

        prev_measured_map = None
        map_window = deque(maxlen=WINDOW)
        hr_window = deque(maxlen=WINDOW)
        spo2_window = deque(maxlen=WINDOW)

        patient_rows = []  # collected per-patient, so we can look ahead after

        for second in range(sim_time):
            patient.update()

            active_flow = patient.flow_rate  # rate BEFORE this tick's decision - no leakage
            decision = expert_controller(patient)

            measured_map = float(np.clip(patient.map + np.random.normal(0, BP_NOISE_SD), 20, 200))
            measured_hr = float(np.clip(patient.hr + np.random.normal(0, HR_NOISE_SD), 30, 220))
            measured_spo2 = float(np.clip(patient.spo2 + np.random.normal(0, SPO2_NOISE_SD), 70, 100))

            if prev_measured_map is None:
                prev_measured_map = measured_map

            measured_bp_error = patient.target_bp - measured_map
            measured_bp_trend = measured_map - prev_measured_map
            measured_shock_index = measured_hr / max(measured_map, 1)
            measured_oxygen_deficit = 100 - measured_spo2
            measured_perfusion = (measured_map * measured_spo2) / 100
            prev_measured_map = measured_map

            # Update rolling windows BEFORE computing stats for this
            # tick, so RollMeanMAP etc. include the current reading.
            map_window.append(measured_map)
            hr_window.append(measured_hr)
            spo2_window.append(measured_spo2)

            roll_mean_map = float(np.mean(map_window))
            roll_std_map = float(np.std(map_window))
            roll_slope_map = _rolling_slope(map_window)
            roll_mean_spo2 = float(np.mean(spo2_window))
            roll_std_spo2 = float(np.std(spo2_window))
            roll_slope_spo2 = _rolling_slope(spo2_window)
            roll_mean_hr = float(np.mean(hr_window))
            roll_slope_hr = _rolling_slope(hr_window)

            patient_rows.append({
                "PatientID": patient.patient_id,
                "Time": second,
                "Profile": patient.profile,

                # Hidden ground-truth demographics/PK - NOT valid AI
                # input features (see module docstring: SAPS_II/Profile
                # are close to the answer key in this simulation).
                "SAPS_II": patient.saps_ii,
                "ClearanceLMin": round(patient.clearance_l_min, 3),
                "VdL": patient.vd_l,

                # TRUE simulated hemodynamics - ground truth / diagnostics
                # only. No real pump/monitor measures SVR, CO, drug
                # effect, or plasma concentration in real time.
                "MAP": round(patient.map, 2),
                "HR": round(patient.hr, 2),
                "SpO2": round(patient.spo2, 2),
                "SVR": round(patient.svr, 1),
                "CO": round(patient.co, 2),
                "DrugEffect": round(patient.drug_effect, 3),
                "PlasmaConcentration": round(patient.plasma_concentration, 3),

                # NOISY sensor readings - valid AI input features
                "MeasuredMAP": round(measured_map, 2),
                "MeasuredHR": round(measured_hr, 2),
                "MeasuredSpO2": round(measured_spo2, 2),
                "MeasuredBP_Error": round(measured_bp_error, 2),
                "MeasuredBP_Trend": round(measured_bp_trend, 2),
                "MeasuredShockIndex": round(measured_shock_index, 2),
                "MeasuredPerfusionIndex": round(measured_perfusion, 2),
                "MeasuredOxygenDeficit": round(measured_oxygen_deficit, 2),

                # Rolling-window features - valid AI input features, and
                # the key ingredient for the risk model: real trend
                # history over the last WINDOW ticks, not a single
                # snapshot.
                "RollMeanMAP": round(roll_mean_map, 2),
                "RollStdMAP": round(roll_std_map, 2),
                "RollSlopeMAP": round(roll_slope_map, 3),
                "RollMeanSpO2": round(roll_mean_spo2, 2),
                "RollStdSpO2": round(roll_std_spo2, 2),
                "RollSlopeSpO2": round(roll_slope_spo2, 3),
                "RollMeanHR": round(roll_mean_hr, 2),
                "RollSlopeHR": round(roll_slope_hr, 3),
                "WindowSize": len(map_window),  # < WINDOW near start of sim

                "FlowRate": round(active_flow, 2),
                "WeightKg": round(patient.weight_kg, 1),
                "Age": patient.age,
                "TargetBP": patient.target_bp,

                "ShockIndex": decision["ShockIndex"],
                "PerfusionIndex": decision["PerfusionIndex"],
                "OxygenDeficit": decision["OxygenDeficit"],
                "BP_Error": decision["BP_Error"],
                "BP_Trend": decision["BP_Trend"],

                "AI_Action": decision["Mode"],
                "ClinicalExplanation": decision["ClinicalExplanation"],
                "RecommendedFlow": decision["RecommendedFlow"],
                "Confidence": decision["Confidence"],
                "StabilityScore": decision["StabilityScore"]
            })

            patient.flow_rate = decision["RecommendedFlow"]

        # ---- Second pass: look ahead into this patient's OWN future ----
        # trajectory to build the risk label. Only possible here, after
        # the full simulation - expert_controller() never has this
        # information, which is what makes it a genuinely independent
        # prediction task rather than imitation.
        true_map_seq = [r["MAP"] for r in patient_rows]
        true_spo2_seq = [r["SpO2"] for r in patient_rows]

        for i, r in enumerate(patient_rows):
            future_map = true_map_seq[i + 1: i + 1 + LOOKAHEAD]
            future_spo2 = true_spo2_seq[i + 1: i + 1 + LOOKAHEAD]
            will_deteriorate = (any(m < EMERGENCY_MAP_MMHG for m in future_map)
                                or any(s < 90 for s in future_spo2))
            r[RISK_LABEL_COLUMN] = int(will_deteriorate)
            r["LookaheadTicksAvailable"] = len(future_map)  # < LOOKAHEAD near end of sim

        rows.extend(patient_rows)

    dataset = pd.DataFrame(rows)
    dataset.to_csv(output_file, index=False)

    print(dataset.shape)
    print("Profile distribution (per patient):")
    print(dataset.groupby("PatientID")["Profile"].first().value_counts())
    print("AI_Action distribution:")
    print(dataset["AI_Action"].value_counts(normalize=True).round(3))
    print(f"{RISK_LABEL_COLUMN} distribution:")
    print(dataset[RISK_LABEL_COLUMN].value_counts(normalize=True).round(3))
    print("FlowRate == RecommendedFlow (should be False):",
          (dataset["FlowRate"] == dataset["RecommendedFlow"]).all())
    print("MAP range:", dataset["MAP"].min(), "-", dataset["MAP"].max())

    return dataset


def plot_patient(dataset, patient_id, title_suffix=""):
    sample = dataset[dataset.PatientID == patient_id]

    plt.figure(figsize=(10, 5))
    plt.plot(sample["Time"], sample["MAP"], label="MAP")
    plt.axhline(sample["TargetBP"].iloc[0], linestyle="--", label="Target MAP")
    plt.xlabel("Time (s)")
    plt.ylabel("MAP (mmHg)")
    profile = sample["Profile"].iloc[0]
    plt.title(f"Patient {patient_id} ({profile}) MAP Response {title_suffix}")
    plt.legend()
    plt.grid()

    plt.figure(figsize=(10, 5))
    plt.plot(sample["Time"], sample["FlowRate"], label="Flow Rate")
    plt.xlabel("Time (s)")
    plt.ylabel("mL/hr")
    plt.title(f"Patient {patient_id} ({profile}) Infusion Flow Rate {title_suffix}")
    plt.grid()


if __name__ == "__main__":
    import os
    os.makedirs("data", exist_ok=True)
    os.makedirs("figures", exist_ok=True)

    # Patient-level 210/30/60 split (of 300 total) - 70/10/20-of-TOTAL,
    # mirroring generate_hypertensive_dataset.py's split ratio and its
    # independent-seed-per-split, whole-patient (not row-level)
    # methodology. Test is kept at the pre-existing 60 patients so
    # already-reported test-set figures elsewhere stay valid; train
    # drops from 250 to 210 and a new 30-patient validation split is
    # added to make room for it within the same 70/10/20 total.
    train_df = generate_dataset(
        num_patients=210, sim_time=600, seed=1,
        output_file="data/train_patients.csv"
    )

    val_df = generate_dataset(
        num_patients=30, sim_time=600, seed=777,
        output_file="data/val_patients.csv"
    )

    test_df = generate_dataset(
        num_patients=60, sim_time=600, seed=999,
        output_file="data/test_patients.csv"
    )

    # Patient-level leakage check (should be empty set) - see
    # generate_hypertensive_dataset.py's identical check for why this
    # is on (seed, patient_id) pairs rather than PatientID alone.
    train_keys = {(1, pid) for pid in train_df["PatientID"].unique()}
    val_keys = {(777, pid) for pid in val_df["PatientID"].unique()}
    test_keys = {(999, pid) for pid in test_df["PatientID"].unique()}
    overlap = (train_keys & val_keys) | (train_keys & test_keys) | (val_keys & test_keys)
    print(f"\nPatient-level leakage check (should be empty set): {overlap}")

    # Saved to disk rather than plt.show() - this is a batch/headless
    # script (train_ai.py and train_risk_model.py already follow this
    # convention for their own figures), and plt.show() has no display
    # to show anything on in that context.
    for profile in ["Healthy", "Severe"]:
        match = train_df[train_df.Profile == profile]
        if not match.empty:
            plot_patient(train_df, match["PatientID"].iloc[0], title_suffix="(train)")
            # plot_patient() always creates the MAP figure first, then
            # the flow-rate figure - the last two open figures, in order.
            map_fignum, flow_fignum = plt.get_fignums()[-2:]
            plt.figure(map_fignum).savefig(f"figures/example_{profile.lower()}_map.png", dpi=150)
            plt.figure(flow_fignum).savefig(f"figures/example_{profile.lower()}_flow.png", dpi=150)
    plt.close("all")

    print("\nTrain and test datasets generated successfully.")
    print(f"Action/flow model features: {FEATURE_COLUMNS}")
    print(f"Risk model features: {RISK_FEATURE_COLUMNS}")
    print(f"Risk label: {RISK_LABEL_COLUMN} (lookahead={LOOKAHEAD} ticks)")
    print("Profile/SAPS_II/ClearanceLMin/VdL/SVR/CO/DrugEffect/PlasmaConcentration "
          "are hidden ground truth - do not use as model inputs.")

