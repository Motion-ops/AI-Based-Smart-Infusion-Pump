"""
===============================================================================
CARDIOVASCULAR.PY
Smart AI Infusion Pump - Mechanistic Digital Twin

Purpose
-------
This module models the patient's cardiovascular response to
norepinephrine infusion by updating the principal haemodynamic
variables responsible for maintaining tissue perfusion.

Using the pharmacodynamic effect generated by the drug model together
with the patient's physiological state, this module computes:

    • Systemic vascular resistance (SVR)
    • Stroke volume (SV)
    • Cardiac output (CO)
    • Mean arterial pressure (MAP)

These variables represent the central cardiovascular state of the
digital twin and are subsequently used by other physiological modules,
including the baroreflex controller.

Model equations
---------------
The cardiovascular relationships implemented in this module follow
well-established physiological principles:

    SVR = SVR₀ × (1 + E)

        Drug-induced increase in systemic vascular resistance.

    SV = SV₀ × (BV/BV₀)

        Simplified representation of the Frank-Starling mechanism,
        relating stroke volume to circulating blood volume.

    CO = HR × SV / 1000

        Cardiac output calculated from heart rate and stroke volume.

    MAP = CVP + (SVR × CO) / 80

        Standard haemodynamic relationship obtained by rearranging
        the systemic vascular resistance equation.

Model assumptions
-----------------
This module adopts simplified cardiovascular relationships that
capture the dominant physiological effects of norepinephrine while
remaining computationally efficient for real-time simulation.

Rather than modelling ventricular mechanics, vascular compliance, and
complete pressure-volume loops, these equations provide a clinically
realistic approximation of cardiovascular behaviour appropriate for a
mechanistic digital twin.

All baseline parameter values and supporting literature references are
documented in constants.py.
===============================================================================
"""

import constants as c


def compute_svr(svr0, drug_effect):
    """
    Computes the current systemic vascular resistance (SVR).

    Parameters
    ----------
    svr0 : float
        Patient's baseline systemic vascular resistance.

    drug_effect : float
        Normalized pharmacodynamic effect generated by the Emax model.

    Returns
    -------
    float
        Updated systemic vascular resistance.

    Explanation
    -----------
    Norepinephrine primarily acts by stimulating α₁-adrenergic
    receptors, producing peripheral vasoconstriction.

    Increased vascular tone raises systemic vascular resistance,
    allowing arterial pressure to recover during hypotensive states.

    The pharmacodynamic effect calculated in pharmacodynamics.py is
    therefore used as a multiplicative scaling factor applied to the
    patient's baseline vascular resistance.
    """

    return svr0 * (1 + drug_effect)


def compute_stroke_volume(sv0_ml, blood_volume_fraction):
    """
    Computes the patient's stroke volume.

    Parameters
    ----------
    sv0_ml : float
        Baseline stroke volume (mL).

    blood_volume_fraction : float
        Current circulating blood volume expressed as a fraction of the
        patient's normal blood volume.

    Returns
    -------
    float
        Updated stroke volume (mL).

    Explanation
    -----------
    According to the Frank-Starling mechanism, ventricular filling
    (preload) is a major determinant of stroke volume.

    As circulating blood volume decreases, venous return to the heart
    is reduced, resulting in a corresponding decrease in stroke volume.

    To avoid unnecessary model complexity, this relationship is
    represented by a simple linear approximation rather than the full
    nonlinear Frank-Starling curve.
    """

    return sv0_ml * blood_volume_fraction


def compute_cardiac_output(hr_bpm, sv_ml):
    """
    Computes cardiac output.

    Parameters
    ----------
    hr_bpm : float
        Heart rate (beats/min).

    sv_ml : float
        Stroke volume (mL/beat).

    Returns
    -------
    float
        Cardiac output (L/min).

    Explanation
    -----------
    Cardiac output represents the total volume of blood pumped by the
    heart each minute.

    It is calculated as the product of heart rate and stroke volume.
    Since stroke volume is expressed in millilitres, division by 1000
    converts the result into litres per minute.
    """

    return hr_bpm * sv_ml / 1000.0


def compute_map(co_l_min,
                svr_dyn_s_cm5,
                cvp_mmhg=c.CVP_TYPICAL_MMHG):
    """
    Computes mean arterial pressure (MAP).

    Parameters
    ----------
    co_l_min : float
        Cardiac output (L/min).

    svr_dyn_s_cm5 : float
        Systemic vascular resistance.

    cvp_mmhg : float, optional
        Central venous pressure (mmHg). A typical physiological value
        is used unless otherwise specified.

    Returns
    -------
    float
        Mean arterial pressure (mmHg).

    Explanation
    -----------
    Mean arterial pressure is calculated using the standard
    haemodynamic relationship:

        MAP = CVP + (SVR × CO) / 80

    This equation reflects the combined influence of cardiac output,
    vascular resistance, and central venous pressure on systemic
    arterial pressure.

    Because norepinephrine primarily increases systemic vascular
    resistance, changes in drug effect propagate through this equation
    to produce the simulated blood pressure response.
    """

    return cvp_mmhg + (svr_dyn_s_cm5 * co_l_min) / 80.0