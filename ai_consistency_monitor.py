"""
===============================================================================
AI_CONSISTENCY_MONITOR.PY
Smart AI Infusion Pump – AI Recommendation Consistency Monitor

Purpose
-------
This module evaluates the level of agreement between the artificial
intelligence recommendations and the deterministic expert controller.

The module performs monitoring only and is intentionally excluded from
the closed-loop control pathway.

Safety Architecture
-------------------
The expert controller is the sole component responsible for determining
the infusion rate delivered to the virtual patient.

The artificial intelligence models provide advisory recommendations
only.

Consequently:

    • AI predictions never directly modify the infusion pump.

    • The expert controller always determines the delivered flow rate.

    • The AI serves as an independent decision-support system whose
      recommendations may be reviewed by a clinician.

This architecture ensures that inaccurate AI predictions cannot
directly influence patient treatment while still allowing the
performance of the machine learning models to be evaluated throughout
the simulation.

Consistency Assessment
----------------------
Three independent comparisons are performed:

    • Agreement between the recommended clinical actions.

    • Agreement between the recommended infusion flow rates.

    • Detection of situations where the controller identifies an
      emergency but the AI does not.

Any clinically meaningful disagreement is reported for subsequent
display, logging, or clinician review.

Implementation Note
-------------------
The default flow disagreement threshold represents a generic fallback.

During normal simulation, the dashboard computes an individualized
threshold based on one clinically meaningful titration step for the
current patient.

This allows disagreement to be assessed relative to patient-specific
dosing requirements rather than using a fixed flow-rate difference for
all patients.
===============================================================================
"""


def evaluate_ai_recommendation(
    expert_decision,
    ai_action,
    ai_suggested_flow,
    flow_disagreement_threshold=5.0,):
    """
    Compares the recommendations produced by the artificial intelligence
    models with the decision generated by the expert controller.

    Parameters
    ----------
    expert_decision : dict
        Decision generated by the deterministic expert controller.

        This represents the actual treatment applied to the simulated
        patient.

    ai_action : str
        Clinical action predicted by the AI classification model.

    ai_suggested_flow : float
        Infusion flow rate predicted by the AI regression model.

    flow_disagreement_threshold : float, optional
        Maximum acceptable difference between the controller's flow rate
        and the AI recommendation before disagreement is reported.

    Returns
    -------
    dict
        Summary of agreement between both decision systems.

    Explanation
    -----------
    This function performs comparison only.

    It never modifies the infusion flow rate and is deliberately kept
    outside the safety-critical control pathway.

    The returned information is intended for visualization,
    performance assessment, and clinician review.
    """
    controller_flow = expert_decision["RecommendedFlow"]
    controller_mode = expert_decision["Mode"]

    flow_divergence = round(abs(ai_suggested_flow - controller_flow), 2)
    action_agrees = (ai_action == controller_mode)
    flow_agrees = flow_divergence <= flow_disagreement_threshold

    alert = None
    if controller_mode == "Emergency" and ai_action != "Emergency":
        alert = "AI did not flag this as an emergency, but the controller did. Sensor or model review recommended."
    elif not action_agrees:
        alert = f"AI recommended '{ai_action}' while the controller chose '{controller_mode}'."
    elif not flow_agrees:
        alert = f"AI flow suggestion diverges from the controller by {flow_divergence} mL/hr."

    return {
        "ControllerFlow": controller_flow,      # what actually drives the patient
        "ControllerMode": controller_mode,
        "AI_Action": ai_action,
        "AI_SuggestedFlow": round(ai_suggested_flow, 2),
        "FlowDivergence": flow_divergence,
        "ActionAgrees": action_agrees,
        "FlowAgrees": flow_agrees,
        "Alert": alert
    }
